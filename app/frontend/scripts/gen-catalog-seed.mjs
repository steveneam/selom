/**
 * Generate the Selom-native half of the Skill-Store seed from the backend's own `skill.json` files.
 *
 * WHY THIS EXISTS. `lib/catalog/seed.ts` was hand-maintained, and by 2026-08-04 it listed 25 of the
 * 44 skills the backend actually serves. That staleness was invisible while `getSkill` read the seed
 * alone — the 19 missing skills rendered as their raw id with a "Queued" badge and a DISABLED Apply,
 * so every plot type built across several sessions was installable and then dead. `getSkill` now
 * prefers the live registry, which makes the drift harmless *while the backend is up*; a
 * backend-down session still shows the seed, and a 19-skill-stale seed is still wrong.
 *
 * The fix is not "refill it carefully". A hand-maintained mirror of a live registry goes stale again
 * — that is the lesson, not the incident [[selom-shipped-not-reachable]]. So the Selom block is
 * GENERATED from the same `skill.json` files `skills/registry.py` reads, and
 * `lib/catalog/registry-completeness.test.ts` re-runs {@link buildSelomSeed} and fails on any
 * difference. Regenerating is `npm run gen:seed`; the guard is what makes forgetting impossible.
 *
 * The hand-authored ClawBio / bioSkills long-tail in `seed.ts` is untouched — those have no
 * `skill.json` and are genuinely curated copy.
 *
 * INVARIANT: {@link toCatalogEntry} must stay a faithful port of `skills/registry.py`
 * `to_catalog_entry`. It is small on purpose. The two are pinned to each other by
 * `test_registry.py::test_catalog_entry_shape` on one side and the drift guard on the other.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const SKILLS_DIR = fileURLToPath(new URL("../../backend/skills", import.meta.url));
export const GENERATED_PATH = fileURLToPath(
  new URL("../lib/catalog/selom-seed.generated.ts", import.meta.url),
);

/** Backend omics tokens → the display facets the FE filters on (mirrors registry.py `_OMICS_DISPLAY`). */
const OMICS_DISPLAY = {
  "scrna-seq": "scRNA-seq",
  "bulk-rna-seq": "bulk RNA-seq",
  proteomics: "proteomics",
  genomics: "genomics",
  metabolomics: "metabolomics",
  epigenomics: "epigenomics",
  spatial: "spatial",
  transcriptomics: "transcriptomics",
};

/** Every `skill.json` on disk, including the `proprietary/<id>/` namespace, sorted by slug. */
function loadSkillJson() {
  const out = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) walk(p);
      else if (entry.name === "skill.json") out.push(JSON.parse(readFileSync(p, "utf8")));
    }
  };
  walk(SKILLS_DIR);
  return out.filter((s) => s?.id).sort((a, b) => a.id.localeCompare(b.id));
}

/** Port of `skills/registry.py` `to_catalog_entry`, restricted to the fields the seed carries. */
export function toCatalogEntry(spec) {
  const cat = spec.catalog ?? {};
  return {
    id: `selom.${spec.id}`,
    // `title` is the ONE display name — a `catalog.name` that shadowed it is refused by
    // `test_registry.py::test_title_is_the_only_display_name`.
    name: spec.title,
    summary: cat.summary || spec.title,
    source: "selom",
    category: cat.category ?? "analysis",
    omics: String(spec.omics ?? "")
      .split("|")
      .filter(Boolean)
      .map((t) => OMICS_DISPLAY[t] ?? t),
    tier: cat.tier ?? "verified",
    status: cat.status ?? "production",
    engine: spec.engine,
    inputFormats: cat.input_formats ?? [],
    chainsWith: (cat.chains_with ?? []).map((c) => `selom.${c}`),
    outputs: (spec.outputs ?? []).map((o) => o.name),
    license: cat.license ?? "MIT",
    provenance: { repo: "selom/skills", path: spec.id },
    version: spec.version,
    popularity: cat.popularity ?? 50,
  };
}

/** The full generated Selom block, in stable slug order. */
export function buildSelomSeed() {
  return loadSkillJson().map(toCatalogEntry);
}

/** Render the block as the generated TS module (deterministic — byte-identical for equal input). */
export function renderModule(entries) {
  const body = entries.map((e) => `  ${JSON.stringify(e)},`).join("\n");
  return `// @generated by scripts/gen-catalog-seed.mjs — DO NOT EDIT BY HAND.
// Source of truth: app/backend/skills/**/skill.json. Regenerate with \`npm run gen:seed\`.
// Drift is a FAILING test (lib/catalog/registry-completeness.test.ts), not a stale file.
import type { SkillCatalogEntry } from "./types";

/** Every skill the backend serves, as Store catalog entries — the offline twin of \`GET /skills\`. */
export const SELOM_SEED: SkillCatalogEntry[] = [
${body}
];
`;
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const entries = buildSelomSeed();
  writeFileSync(GENERATED_PATH, renderModule(entries));
  console.log(`wrote ${entries.length} Selom skills → ${GENERATED_PATH}`);
}
